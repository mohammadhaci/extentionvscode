// Copies the pure (vscode-free) Django parsers from the Django Visual Map
// extension at the repository root into src/vendor/, so both extensions share
// one implementation. src/vendor/ is generated and git-ignored.
const fs = require("fs");
const path = require("path");

const repoSrc = path.resolve(__dirname, "..", "..", "src");
const dest = path.resolve(__dirname, "..", "src", "vendor");
const files = [
  "analyzer/appDiscovery.ts",
  "analyzer/parseModels.ts",
  "analyzer/parseSettings.ts",
  "analyzer/parseUrls.ts",
  "analyzer/pythonHeuristics.ts",
  "analyzer/decodePythonSource.ts",
  "shared/graphTypes.ts",
];

fs.rmSync(dest, { recursive: true, force: true });
for (const f of files) {
  const from = path.join(repoSrc, f);
  const to = path.join(dest, f);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  const header = `// GENERATED by scripts/vendor-analyzer.js from src/${f} at the repo root. Do not edit.\n`;
  fs.writeFileSync(to, header + fs.readFileSync(from, "utf8"));
}
console.log(`vendored ${files.length} parser files into src/vendor/`);

// The CI workflow template (ci/agent-guardrails.yml) is embedded so the CLI
// installed in a project can write it without the extension's files.
const ci = fs.readFileSync(path.resolve(__dirname, "..", "ci", "agent-guardrails.yml"), "utf8");
fs.writeFileSync(
  path.join(dest, "ciTemplate.ts"),
  "// GENERATED by scripts/vendor-analyzer.js from ci/agent-guardrails.yml. Do not edit.\n" +
    `export const CI_WORKFLOW = ${JSON.stringify(ci)};\n`
);
console.log("embedded ci/agent-guardrails.yml into src/vendor/ciTemplate.ts");
