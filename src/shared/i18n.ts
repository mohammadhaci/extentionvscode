export const SUPPORTED_LANGS = ["en", "de", "ar"] as const;
export type SupportedLang = (typeof SUPPORTED_LANGS)[number];

export function isSupportedLang(v: unknown): v is SupportedLang {
  return v === "en" || v === "de" || v === "ar";
}

/** Normalize unknown input (webview state, selector value) to a language. */
export function resolveLang(v: unknown): SupportedLang {
  return isSupportedLang(v) ? v : "en";
}

/** Text direction for a language. Code identifiers/paths stay LTR via CSS. */
export function langDir(lang: SupportedLang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function languageName(lang: SupportedLang): string {
  if (lang === "de") {
    return "Deutsch";
  }
  if (lang === "ar") {
    return "العربية";
  }
  return "English";
}

