export const UI_STRINGS: Record<SupportedLang, Dict> = { en, de, ar };

/** All dictionaries must expose exactly the same keys (checked in tests). */
export function dictKeys(lang: SupportedLang): string[] {
  return Object.keys(UI_STRINGS[lang]).sort();
}

/** Look up a key with English fallback, then the key itself. */
export function translate(lang: SupportedLang, key: string): string {
  const d = UI_STRINGS[resolveLang(lang)];
  if (Object.prototype.hasOwnProperty.call(d, key)) {
    return d[key];
  }
  if (Object.prototype.hasOwnProperty.call(en, key)) {
    return en[key];
  }
  return key;
}

/** Fill {placeholders} in a template string. Unknown params stay in place. */
export function formatTemplate(tpl: string, params: Record<string, string | number> = {}): string {
  return String(tpl).replace(/\{(\w+)\}/g, (m, name: string) => {
    if (Object.prototype.hasOwnProperty.call(params, name)) {
      return String(params[name]);
    }
    return m;
  });
}

/** Localized lookup + formatting in one call. */
export function t(lang: SupportedLang, key: string, params?: Record<string, string | number>): string {
  return formatTemplate(translate(lang, key), params);
}
